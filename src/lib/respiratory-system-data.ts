function choice(id: string, question: string, options: string[], answer: string, explanation: string): OsteologyQuestion {
  return { id, type: "single_choice", question, options, answer, explanation };
}

function blank(id: string, question: string, answer: string, explanation: string): OsteologyQuestion {
  return { id, type: "fill_blank", question, answer, explanation };
}

function judge(id: string, question: string, answer: boolean, explanation: string): OsteologyQuestion {
  return { id, type: "true_false", question, answer, explanation };
}

function short(id: string, question: string, answer: string, explanation: string): OsteologyQuestion {
  return { id, type: "short_answer", question, answer, explanation };
}

